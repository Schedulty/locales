import { copyFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { LOCALES_DIR, REFERENCE_LOCALE, checkLocales, readLocales } from './check.mjs';

const { files, errors } = readLocales();
errors.push(...checkLocales(files));
if (errors.length > 0) {
  for (const error of errors) console.error(`✗ ${error}`);
  process.exit(1);
}

const locales = Object.keys(files).sort();
const root = (name) => fileURLToPath(new URL(`../${name}`, import.meta.url));
const header = '// Generated by scripts/build.mjs from locales/*.json. Do not edit.\n';

writeFileSync(
  root('index.js'),
  `${header}'use strict';

exports.LOCALES = Object.freeze(${JSON.stringify(locales)});
exports.REFERENCE_LOCALE = '${REFERENCE_LOCALE}';
exports.toLanguageTag = (locale) => locale.replace('_', '-');
`,
);

writeFileSync(
  root('index.d.ts'),
  `${header}
export type Locale = ${locales.map((locale) => `'${locale}'`).join(' | ')};

/** Every shipped locale code, as in the file names. */
export declare const LOCALES: readonly Locale[];

/** The locale every other file is checked against. */
export declare const REFERENCE_LOCALE: '${REFERENCE_LOCALE}';

/** ru_RU → ru-RU, the BCP 47 form Intl and i18next expect. */
export declare function toLanguageTag(locale: Locale): string;

/** Shape of every locale file. Needs "resolveJsonModule" in the consumer's tsconfig. */
export type Resources = typeof import('./${REFERENCE_LOCALE}.json');
`,
);

// Only these root copies ship; `exports` maps `./locales/*.json` onto them.
for (const locale of locales) copyFileSync(`${LOCALES_DIR}${locale}.json`, root(`${locale}.json`));

console.log(`✓ index.js, index.d.ts, <locale>.json: ${locales.join(', ')}`);
